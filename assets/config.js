/* config.js —— 所有常量。
   ============================================================
   为什么单独放一个文件：老项目（来源看板）Day 6 定的规矩第 7 条 ——
   **常量只在 config.js**，不许散落在别的文件里。
   后面想调「历史显示几天」「一天完成几项才算打过卡」，
   只改这一个文件，不用去翻代码。

   加载顺序：config.js → rules.js → store.js → data.js → app.js
   （后面每个文件一开头就要用前面那个，顺序不能换）
   ============================================================ */

window.GROWTH_CONFIG = {

  /* ---------- 存储 ---------- */

  /* 浏览器里存打卡记录用的「抽屉名」。
     故意带版本号 v1：以后记录格式改了，换成 v2 就是新抽屉，
     旧数据留在旧抽屉里不会被读错、也不会被误删。 */
  storeKey: 'growth-site.checkins.v1',

  /* 记录格式的版本号，写进数据里。
     读出来发现版本对不上，就按「空记录」处理，不去瞎猜旧格式。 */
  schemaVersion: 1,

  /* 收藏**单独一只抽屉**（Day 12 加）。
     为什么不跟打卡挤在一个抽屉里：两件事的格式以后会各自演化，
     混在一只抽屉里，改收藏的格式就会连累打卡的记录。
     分开放，各改各的、互不影响。 */
  favKey: 'growth-site.favorites.v1',
  favSchemaVersion: 1,

  /* 自己添加的行动项，**第三只抽屉**（Day 14 加）。
     为什么再分一只：打卡抽屉存的是「今天完成了哪些 id」，
     这只存的是「有哪些项目」—— 还是那句话，格式会各自演化，
     挤在一起改一样会连累另一样。 */
  customKey: 'growth-site.custom-actions.v1',
  customSchemaVersion: 1,

  /* 「今日一篇」的已读记录，**第四只抽屉**（Day 15 加）。
     存的是「读过哪几篇」的 id 数组，跟打卡 / 收藏 / 自定义项分开。
     为什么不用同一个键存「哪天读过」：一篇好文章读过了就是读过了，
     一年后再次轮到它，页面上应该仍然认得「你已经读过」。 */
  readKey: 'growth-site.daily-reads.v1',
  readSchemaVersion: 1,

  /* ---------- 内容的形态（Day 15 加） ----------

     四种形态。**为什么只留四种**：形态越多，手工摘录的时候越要停下来想
     「这条算哪种」；想的次数多了，最后就会懒得标 —— 那这个字段就废了。

     label 是页面上显示的字；short 是给以后写小屏留的（现在没用上）。 */
  media: {
    video:   { label: '视频',   short: '看' },
    article: { label: '文章',   short: '读' },
    podcast: { label: '播客',   short: '听' },
    talk:    { label: '长访谈', short: '看' }
  },

  /* 形态认不出来时按哪种算（空、拼错、数字、整个字段没有，都落到这里）。
     选「文章」是因为它最中性 —— 它不会让用户以为「必须点开看视频」。
     ⚠️ 认不出来**不报错**，这跟其它字段一个规矩：
     外面来的数据不许假设它长得对。 */
  mediaDefault: 'article',

  /* 「今日一篇」按天轮换的**起算日**（Day 15 加）。
     dayNumber = 今天跟这一天的天数差，再对候选池取余 —— 所以
     同一天永远是同一篇，第二天自动换下一篇，而且**不会短期重复**。
     换这个日期 = 重新洗一次轮换顺序，平时不用动它。 */
  readEpoch: '2026-10-01',

  /* ---------- 自定义行动项的规矩（Day 14 加） ---------- */

  /* 最多能加几项。默认那 3 项不算在里面。
     为什么卡 10：一屏列二十项就不是「每天三件事」了，产品定位会散。 */
  customMax: 10,

  /* 每项最多几个字。输入框的 maxlength 直接用它。
     为什么 24：这是「今天要做的事」，本来就该一句话说完；
     太长会把行动卡撑变形。 */
  customTextMax: 24,

  /* ---------- 打卡规则 ---------- */

  /* 一天至少完成几项，才算「这天打过卡」（影响连续天数怎么数）。
     1 = 只要动过一项就算，门槛低、不容易断，适合养成阶段。 */
  minPerDay: 1,

  /* 行动卡下面显示最近几天的记录格子 */
  historyDays: 7,

  /* 打卡后那句「已记下」提示停留多久（毫秒）。
     2.5 秒：够看清楚，又不至于挡着下面的内容。
     想让它更快消失 / 停更久，改这一个数。 */
  noticeMs: 2500,

  /* 数连续天数时最多往回找多少天，防止数据出问题时卡死 */
  streakLimit: 3650,

  /* ---------- 视图与地址（Day 13 加） ---------- */

  /* 地址前缀。三个视图的地址就是 '#/home'、'#/library'、'#/me'。
     为什么用地址里那截「#」：浏览器不会拿它去请求服务器，
     本地双击 html 打开（file://）也能用 —— 换成真正的路径就得有服务器配合。
     三个视图各自叫什么叫什么、按什么顺序排，在 data.js 的 views 里
     （那是文案和顺序，属于内容）。 */
  route: {
    prefix: '#/',
    /* 地址认不出来时（空的 / 手打错一个字母）回哪个视图。
       没有这条兜底，用户打错一个字母就会看到白屏。 */
    defaultId: 'home'
  },

  /* 列表「读取内容」的模拟延迟（毫秒）。
     为什么故意留一个延迟：
       现在数据就在本地，不留延迟的话「加载中」这个状态一帧就过去了，
       肉眼根本看不见 —— 而清单要求四种状态都得看得到。
       以后内容真从服务器取，也一定会先有这么一个「正在读取」的瞬间，
       所以这一层不是白留的。
     想让它瞬间出来，把这里改成 0。 */
  listDelayMs: 420,

  /* 「加载中」的时候先画几条灰条占位（骨架屏），免得一片空白让人以为卡住了 */
  skeletonRows: 3

};
